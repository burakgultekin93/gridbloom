// ignore_for_file: avoid_print
// Writes lib/firebase_options.dart from the two files Firebase gives you.
//
// 1. Put GoogleService-Info.plist in ios/Runner/
// 2. Put google-services.json in android/app/ (optional until Android launch)
// 3. Run: dart run tool/firebase_setup.dart
//
// No Firebase CLI, Gradle plugin or Xcode changes are needed: the game passes
// these values to Firebase itself.
import 'dart:convert';
import 'dart:io';

const bundleId = 'com.burakgultekin.blazegrid';

void main() {
  final ios = _ios(File('ios/Runner/GoogleService-Info.plist'));
  final android = _android(File('android/app/google-services.json'));
  if (ios == null && android == null) {
    print('Neither ios/Runner/GoogleService-Info.plist nor android/app/google-services.json was found.');
    exit(1);
  }
  File('lib/firebase_options.dart').writeAsStringSync(_render(ios, android));
  print('lib/firebase_options.dart written (iOS: ${ios != null ? 'yes' : 'no'}, Android: ${android != null ? 'yes' : 'no'}).');
}

Map<String, String>? _ios(File f) {
  if (!f.existsSync()) return null;
  final text = f.readAsStringSync();
  String? key(String k) => RegExp('<key>$k</key>\\s*<string>([^<]*)</string>').firstMatch(text)?.group(1);
  final bundle = key('BUNDLE_ID');
  if (bundle != null && bundle != bundleId) {
    print('Warning: the plist is for "$bundle", the app is "$bundleId".');
  }
  final out = {
    'apiKey': key('API_KEY'),
    'appId': key('GOOGLE_APP_ID'),
    'messagingSenderId': key('GCM_SENDER_ID'),
    'projectId': key('PROJECT_ID'),
    'storageBucket': key('STORAGE_BUCKET'),
    'iosBundleId': bundle ?? bundleId,
  };
  return _complete('GoogleService-Info.plist', out);
}

Map<String, String>? _android(File f) {
  if (!f.existsSync()) return null;
  final j = jsonDecode(f.readAsStringSync()) as Map<String, dynamic>;
  final info = j['project_info'] as Map<String, dynamic>;
  final clients = (j['client'] as List).cast<Map<String, dynamic>>();
  final client = clients.firstWhere(
    (c) => c['client_info']?['android_client_info']?['package_name'] == bundleId,
    orElse: () {
      print('Warning: google-services.json has no app for "$bundleId", using its first app.');
      return clients.first;
    },
  );
  final out = {
    'apiKey': (client['api_key'] as List).first['current_key'] as String?,
    'appId': client['client_info']['mobilesdk_app_id'] as String?,
    'messagingSenderId': info['project_number'] as String?,
    'projectId': info['project_id'] as String?,
    'storageBucket': info['storage_bucket'] as String?,
  };
  return _complete('google-services.json', out);
}

Map<String, String>? _complete(String name, Map<String, String?> m) {
  final missing = [
    for (final k in ['apiKey', 'appId', 'messagingSenderId', 'projectId'])
      if (m[k] == null || m[k]!.isEmpty) k,
  ];
  if (missing.isNotEmpty) {
    print('$name is missing ${missing.join(', ')}; skipped.');
    return null;
  }
  return {
    for (final e in m.entries)
      if (e.value != null && e.value!.isNotEmpty) e.key: e.value!,
  };
}

String _options(Map<String, String>? m) {
  if (m == null) return 'null';
  final b = StringBuffer('FirebaseOptions(\n');
  m.forEach((k, v) => b.writeln("    $k: '$v',"));
  b.write('  )');
  return b.toString();
}

String _render(Map<String, String>? ios, Map<String, String>? android) =>
    '''
// Firebase connection settings for Blazegrid.
//
// Generated by `dart run tool/firebase_setup.dart` from
// ios/Runner/GoogleService-Info.plist and android/app/google-services.json.
// Until those files are added this returns null and the game simply uses the
// built-in defaults from lib/game/game_config.dart.
// ignore_for_file: type=lint
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart' show defaultTargetPlatform, kIsWeb, TargetPlatform;

class DefaultFirebaseOptions {
  /// Options for the running platform, or null when it isn't set up.
  static FirebaseOptions? get currentPlatform {
    if (kIsWeb) return null;
    return switch (defaultTargetPlatform) {
      TargetPlatform.iOS => ios,
      TargetPlatform.android => android,
      _ => null,
    };
  }

  static const FirebaseOptions? ios = ${_options(ios)};

  static const FirebaseOptions? android = ${_options(android)};
}
''';
